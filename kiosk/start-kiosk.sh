#!/usr/bin/env bash
# ============================================================
#  Smart Attendance – Kiosk Launcher (Sumaiya's Mac)
#
#  Works over LAN *or* the open internet (via a tunnel URL).
#
#  HOW TO USE
#  ----------
#  Your friend runs the backend + tunnel (see start-server.sh).
#  They will give you a URL like:
#       https://abc123.trycloudflare.com
#
#  Option A – set env var before running:
#       export BACKEND_URL=https://abc123.trycloudflare.com
#       ./kiosk/start-kiosk.sh
#
#  Option B – hard-code the URL below (BACKEND_URL= line).
#
#  Option C – same LAN / hotspot (no tunnel needed):
#       export BACKEND_URL=http://192.168.1.42:8000
#       ./kiosk/start-kiosk.sh
#
#  The kiosk opens at:  http://localhost:5173/kiosk
# ============================================================

set -e

# ── Configurable ─────────────────────────────────────────────
# Accepts any URL: Cloudflare tunnel, ngrok, local IP, etc.
BACKEND_URL="${BACKEND_URL:-}"

if [[ -z "$BACKEND_URL" ]]; then
  echo ""
  echo "ERROR: BACKEND_URL is not set."
  echo ""
  echo "  Your friend should share the tunnel URL, e.g.:"
  echo "    https://abc123.trycloudflare.com"
  echo ""
  echo "  Then run:"
  echo "    export BACKEND_URL=https://abc123.trycloudflare.com"
  echo "    ./kiosk/start-kiosk.sh"
  echo ""
  exit 1
fi

# Strip trailing slash for consistency
BACKEND_URL="${BACKEND_URL%/}"

echo ""
echo "╔══════════════════════════════════════════════╗"
echo "║   Smart Attendance  –  Kiosk Terminal Mode   ║"
echo "╚══════════════════════════════════════════════╝"
echo ""
echo "  Backend URL : ${BACKEND_URL}"
echo "  API base    : ${BACKEND_URL}/api"
echo "  Kiosk page  : http://localhost:5173/kiosk"
echo ""

# ── Navigate to frontend directory ───────────────────────────
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
FRONTEND_DIR="$(cd "$SCRIPT_DIR/../frontend" && pwd)"
cd "$FRONTEND_DIR"

# ── Write a temporary runtime env file ───────────────────────
# We set VITE_BACKEND_TARGET so Vite's proxy forwards /api to the friend's laptop,
# while keeping VITE_API_URL empty/omitted so the browser sends same-origin '/api' requests.
# This completely eliminates CORS issues!
cat > .env.kiosk <<EOF
# Auto-generated by kiosk/start-kiosk.sh — do NOT commit this file
VITE_BACKEND_TARGET=${BACKEND_URL}
VITE_API_URL=
EOF

echo "✓  Wrote .env.kiosk"

# ── Cleanup env file on exit ──────────────────────────────────
cleanup() { rm -f "$FRONTEND_DIR/.env.kiosk"; }
trap cleanup EXIT

# ── Start Vite ───────────────────────────────────────────────
node_modules/.bin/vite \
  --port 5173 \
  --mode kiosk
